#!/usr/bin/env python3
"""Lists every file under assets/ for the game to preload into RAM.

core/assetfs.c reads each path named here at startup; after that no screen
change, level change or door touches the disk. Run this (`make manifest`)
after adding or renaming an asset. A file left out still works -- it is
read when first asked for and the game says so -- it just is not preloaded.
"""

import argparse
from pathlib import Path

# (build 130) Directories under assets/ the game never reads: assets/icon/
# holds the Windows icon and the portrait it is made from, which windres
# (src/platform/ps2.rc) and tools/make_icon.py read at build time. Left out
# of the preload list and of `make dist`'s pack (tools/make_pack.py).
NOT_READ_BY_GAME = ("icon",)

# (build 132a) Listings no loader opens (src/ names none of them): the
# extractors write them for tools and for reading by eye -- extract_art.py
# colours its tile sheets from palettes.json. Kept in assets/, left out of
# the preload list and of `make dist`'s pack, as icon/ is.
NOT_READ_FILES = ("music/songs.json", "nametables/nametables.json",
                  "palettes/palettes.json", "winart.json")
# (build 137a) The game reads the FM instruments (fm_instruments.json, out of
# this list since 137a) and the song text, which it builds its sound image
# from; nothing is left out by directory. (build 139b) The songs' tracker
# files (music/songs/*.trk) too: the game reads a song's .trk in place of
# its stream text, so they are listed beside the song files.
NOT_READ_DIRS = ()


def read_by_game(path, root):
    """False for a file under one of NOT_READ_BY_GAME, or one of
    NOT_READ_FILES."""
    rel = path.relative_to(root)
    if rel.as_posix() in NOT_READ_FILES:
        return False
    if any(rel.as_posix().startswith(d + "/") for d in NOT_READ_DIRS):
        return False
    return not (len(rel.parts) > 1 and rel.parts[0] in NOT_READ_BY_GAME)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root", type=Path, nargs="?", default=Path("assets"))
    args = ap.parse_args()

    out = args.root / "manifest.txt"
    # Left out: formats read once at startup by loaders that decode them
    # straight into their final structures (tables and sound data, .bin),
    # and Tiled's own tileset files, which the game never opens. (build 134)
    # The window maps were .map containers, left out the same way; they are
    # Tiled maps now, read through the store and listed. (build 135) So are
    # the screen nametables, .nam containers until then. (build 137a) The
    # last .bin, SoundData.bin, is the song text now: .bin is off this list.
    skip_suffix = {".tsx", ".bak"}
    paths = sorted(p.as_posix() for p in args.root.rglob("*")
                   if p.is_file() and p != out
                   and read_by_game(p, args.root)
                   and p.suffix not in skip_suffix
                   and not p.name.startswith("."))

    total = sum(Path(p).stat().st_size for p in paths)
    out.write_text("# Files preloaded into RAM at startup. Generated by "
                   "tools/make_manifest.py.\n" + "\n".join(paths) + "\n", newline="\n")
    print(f"{len(paths)} files, {total / 1e6:.1f} MB -> {out}")


if __name__ == "__main__":
    main()
